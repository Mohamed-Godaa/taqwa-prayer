H = {"User-Agent": "prayerpro-widget/1.0", "Accept": "application/json"}


def lookup(city, country):
    p = {"format": "jsonv2", "limit": "1", "city": city, "country": country,
         "accept-language": "en"}
    req = urllib.request.Request(
        "https://nominatim.openstreetmap.org/search?" + urllib.parse.urlencode(p),
        headers=H)
    d = json.load(urllib.request.urlopen(req, timeout=20))
    if d:
        return d[0]["lat"], d[0]["lon"]
    # retry without country constraint, first result
    p = {"format": "jsonv2", "limit": "1", "q": f"{city}, {country}",
         "accept-language": "en"}
    req = urllib.request.Request(
        "https://nominatim.openstreetmap.org/search?" + urllib.parse.urlencode(p),
        headers=H)
    d = json.load(urllib.request.urlopen(req, timeout=20))
    return (d[0]["lat"], d[0]["lon"]) if d else (None, None)


out = {}
missing = []
for country, cities in PLACES.items():
    rows = []
    for city in cities:
        try:
            la, lo = lookup(city, country)
        except Exception as e:
            print("ERR", country, city, e)
            la, lo = None, None
        time.sleep(1.1)  # Nominatim usage policy
        if la:
            rows.append({"n": city, "la": la, "lo": lo})
            print("ok", country, city, la, lo)
        else:
            missing.append((country, city))
            print("MISS", country, city)
    out[country] = rows

